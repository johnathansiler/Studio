import { spawnSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const manifest = resolve(root, 'core/Cargo.toml')
const wasmPath = resolve(root, 'core/target/wasm32-unknown-unknown/release/cueharbor_dsp.wasm')
const outPath = resolve(root, 'src/audio/wasm/dspBytes.ts')
const hashPath = resolve(root, 'src/audio/wasm/dspBytes.sha256')
const force = process.argv.includes('--force')

function cargoOnPath() {
  const probe = spawnSync('cargo', ['--version'], { encoding: 'utf8' })
  return !probe.error && probe.status === 0
}

if (!cargoOnPath()) {
  if (force) {
    console.error('build:dsp needs cargo and the wasm32-unknown-unknown target.')
    process.exit(1)
  }
  if (!existsSync(outPath) || !existsSync(hashPath)) {
    console.error('The committed DSP module is missing, and cargo is not installed.')
    process.exit(1)
  }
  console.log('cargo is not installed. Using the committed DSP module.')
  process.exit(0)
}

const build = spawnSync(
  'cargo',
  ['build', '-p', 'cueharbor-dsp', '--locked', '--release', '--target', 'wasm32-unknown-unknown', '--manifest-path', manifest],
  { cwd: root, stdio: 'inherit' },
)
if (build.error || build.status !== 0) process.exit(build.status || 1)

const wasm = readFileSync(wasmPath)
const hash = createHash('sha256').update(wasm).digest('hex')
const source = `/** Generated by scripts/build-dsp.mjs from core/dsp. EQ DSP code, not a sample library. */\nexport const DSP_WASM_BYTE_LENGTH = ${wasm.length}\nexport const DSP_WASM_BASE64 =\n  ${JSON.stringify(wasm.toString('base64'))}\n`
writeFileSync(outPath, source)
writeFileSync(hashPath, `${hash}\n`)

const artifactDir = '/opt/cursor/artifacts'
try {
  mkdirSync(artifactDir, { recursive: true })
  writeFileSync(resolve(artifactDir, 'cueharbor-dsp.wasm'), wasm)
  writeFileSync(resolve(artifactDir, 'dsp-wasm-size.txt'), `${wasm.length}\n`)
} catch {
  // The module in src/ is what the app build uses. Artifact copies are optional.
}

console.log(`cueharbor-dsp.wasm ${wasm.length} bytes ${hash}`)
