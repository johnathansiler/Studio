import { execFileSync } from 'node:child_process'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const manifest = resolve(root, 'core/Cargo.toml')
const wasmPath = resolve(root, 'core/target/wasm32-unknown-unknown/release/cueharbor_dsp.wasm')
const outPath = resolve(root, 'src/audio/wasm/dspBytes.ts')

execFileSync(
  'cargo',
  ['build', '-p', 'cueharbor-dsp', '--release', '--target', 'wasm32-unknown-unknown', '--manifest-path', manifest],
  { cwd: root, stdio: 'inherit' },
)

const wasm = readFileSync(wasmPath)
const outDir = resolve('/opt/cursor/artifacts')
mkdirSync(outDir, { recursive: true })
writeFileSync(resolve(outDir, 'cueharbor-dsp.wasm'), wasm)
writeFileSync(resolve(outDir, 'dsp-wasm-size.txt'), `${wasm.length}\n`)

const source = `/** Generated by scripts/build-dsp.mjs from core/dsp. EQ DSP code, not a sample library. */\nexport const DSP_WASM_BYTE_LENGTH = ${wasm.length}\nexport const DSP_WASM_BASE64 =\n  ${JSON.stringify(wasm.toString('base64'))}\n`
writeFileSync(outPath, source)
console.log(`cueharbor-dsp.wasm ${wasm.length} bytes`)
